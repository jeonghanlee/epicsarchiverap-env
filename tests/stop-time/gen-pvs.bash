#!/usr/bin/env bash
# Generate the 2097 PVs that turn the 903-PV test set of ansible-provision into
# the stage of 3000 PVs: the IOC database extra.db and the PV list extra.csv.
# Usage: gen-pvs.bash <output folder>
# The records have the form of load1.db of ansible-provision; the output is
# deterministic and ends its lines with LF.

set -euo pipefail

readonly COUNT=2097
readonly PREFIX="STOPTIME:E"

function usage {
    printf 'Usage: %s <output folder>\n' "$(basename "$0")" >&2
    exit 3
}

function main {
    [[ $# -eq 1 ]] || usage
    local out="$1"
    [[ -d "${out}" ]] || { printf 'gen-pvs: not a folder: %s\n' "${out}" >&2; exit 3; }
    local db="${out}/extra.db" csv="${out}/extra.csv"
    local index name
    {
        printf '# Generated by tests/stop-time/gen-pvs.bash; do not edit.\n'
        for ((index = 1; index <= COUNT; index++)); do
            name=$(printf '%s%04d' "${PREFIX}" "${index}")
            printf 'record(calc, "%s") {\n' "${name}"
            printf '  field(SCAN, "1 second")\n'
            printf '  field(INPA, "%s.VAL NPP")\n' "${name}"
            printf '  field(CALC, "(A+1)%%3600")\n'
            printf '  field(VAL, "%d")\n' "$((index * 100))"
            printf '  field(PREC, "1")\n'
            printf '}\n'
            if ((index < COUNT)); then
                printf '\n'
            fi
        done
    } > "${db}"
    {
        printf 'pv,group,scan,method,period,policy,store_key\n'
        for ((index = 1; index <= COUNT; index++)); do
            name=$(printf '%s%04d' "${PREFIX}" "${index}")
            printf '%s,extra,1 second,MONITOR,1.0,,%s\n' "${name}" "${name//:/\/}"
        done
    } > "${csv}"
}

main "$@"
