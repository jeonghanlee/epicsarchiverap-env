#!/usr/bin/env bash
# Generates book/src/appendix/make-targets.md from the Make database and the help text of the Makefile.
# Usage: bash book/scripts/gen-make-targets.bash [OUTPUT_FILE]
set -euo pipefail

top="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
output="${1:-${top}/book/src/appendix/make-targets.md}"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

# Descriptions: the `## text` comment above a target, or after it on the same line, in the files that the
# Makefile includes. This is the rule of `make help`, read from the files so that a colon in the text survives.
{ ls "${top}/Makefile" "${top}"/configure/RULES*; } | while IFS= read -r file; do
    awk '
        /^[a-zA-Z._0-9-]+:/ {
            name = $0; sub(/:.*/, "", name)
            text = ""
            if (previous ~ /^## /) { text = previous; sub(/^## /, "", text) }
            else if ($0 ~ / ## /) { text = $0; sub(/^[^#]* ## /, "", text) }
            gsub(/[ \t]+$/, "", text)
            if (text != "") print name "\t" text
        }
        { previous = $0 }
    ' "${file}"
done > "${work}/help.tsv"

# Targets and prerequisites from the Make database.
{ make -C "${top}" -pRrq : 2>/dev/null || true; } | awk '
    /^# Not a target:/ { skip = 1; next }
    /^[a-zA-Z0-9][a-zA-Z0-9_.-]*:( |$)/ && !/:=/ {
        if (!skip) {
            name = $0; sub(/:.*/, "", name)
            deps = substr($0, length(name) + 2); gsub(/^ +| +$/, "", deps)
            print name "\t" deps
        }
    }
    /^$/ { skip = 0 }
' | grep -v -e '\$' -e '_RULES' | LC_ALL=C sort -u > "${work}/targets.tsv"

{
    cat <<'HEADER'
# Make targets of the repository

<!-- Generated by book/scripts/gen-make-targets.bash from the Make database. Do not edit. -->

This page lists every target that `make` knows in this repository, the prerequisites that run before it, and the description that the Makefile gives it. `make help` prints the targets that have a description. A prerequisite after `|` is an order-only prerequisite.

| Target | Prerequisites | Description |
| :--- | :--- | :--- |
HEADER
    awk -F'\t' -v prefix="${top}/" '
        NR == FNR { desc[$1] = $2; next }
        {
            deps = $2
            while ((pos = index(deps, prefix)) != 0) {
                deps = substr(deps, 1, pos - 1) substr(deps, pos + length(prefix))
            }
            gsub(/\|/, "\\|", deps)
            d = ($1 in desc) ? desc[$1] : ""
            gsub(/\|/, "\\|", d)
            printf "| `%s` | %s | %s |\n", $1, (deps == "" ? "" : "`" deps "`"), d
        }
    ' "${work}/help.tsv" "${work}/targets.tsv"
} > "${output}"
printf 'wrote %s (%s targets)\n' "${output}" "$(wc -l < "${work}/targets.tsv")"
