#!/usr/bin/env bash
# Generates book/src/configure/policy-parameters.md from the class comment of the PlainPB storage plugin.
# Usage: bash book/scripts/gen-policy-parameters.bash [OUTPUT_FILE]
set -euo pipefail

top="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
source_file="${top}/epicsarchiverap-maven-src/src/main/edu/stanford/slac/archiverappliance/PlainPB/PlainPBStoragePlugin.java"
output="${1:-${top}/book/src/configure/policy-parameters.md}"
[[ -f "${source_file}" ]] || { printf 'missing %s (run make init)\n' "${source_file}" >&2; exit 1; }

{
    cat <<'HEADER'
# Storage policy parameters

<!-- Generated by book/scripts/gen-policy-parameters.bash from the class comment of PlainPBStoragePlugin. Do not edit. -->

A store of the appliance is a URL of the form `pb://<host>?name=<name>&rootFolder=<folder>&<parameter>=<value>`. The class `PlainPBStoragePlugin` of the source reads the parameters, and its class comment describes each one. `policies.py` builds these URLs for the policies of the appliance.

The table repeats the class comment of the source commit that the repository builds (`make -s print-SRC_TAG`).

| Parameter | Description |
| :--- | :--- |
HEADER
    awk '
        function clean(s) {
            gsub(/<code>|<\/code>/, "`", s)
            gsub(/&amp;/, "\\&", s)
            gsub(/&lt;/, "<", s)
            gsub(/&gt;/, ">", s)
            gsub(/<a href="[^"]*">/, "", s)
            gsub(/<\/a>/, "", s)
            gsub(/<[^>]+>/, "", s)
            gsub(/\|/, "\\|", s)
            gsub(/[ \t]+/, " ", s)
            sub(/^ /, "", s); sub(/ $/, "", s)
            return s
        }
        /^ \* <dl>/ { inside = 1; next }
        /^ \* <\/dl>/ { inside = 0 }
        !inside { next }
        {
            line = $0; sub(/^ \* ?/, "", line)
            if (line ~ /<dt>/) {
                name = line; sub(/.*<dt>/, "", name); sub(/<\/dt>.*/, "", name)
                body = line; sub(/.*<\/dt>/, "", body); sub(/<dd>/, "", body)
                collecting = 1
            } else if (collecting) {
                body = body " " line
            }
            if (collecting && body ~ /<\/dd>/) {
                sub(/<\/dd>.*/, "", body)
                printf "| `%s` | %s |\n", clean(name), clean(body)
                collecting = 0
            }
        }
    ' <(sed -E 's/\{@link [^ }]+ ([^}]*)\}/\1/g; s/\{@link ([^}]*)\}/\1/g' "${source_file}")
} > "${output}"
printf 'wrote %s (%s parameters)\n' "${output}" "$(grep -c '^| `' "${output}")"
