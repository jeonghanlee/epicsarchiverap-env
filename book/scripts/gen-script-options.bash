#!/usr/bin/env bash
# Generates book/src/appendix/script-options.md from the help output of the scripts.
# Usage: bash book/scripts/gen-script-options.bash [OUTPUT_FILE]
set -euo pipefail

top="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
output="${1:-${top}/book/src/appendix/script-options.md}"

section() {
    local title="$1" intro="$2" command="$3"
    shift 3
    # shellcheck disable=SC2016
    printf '## %s\n\n%s\n\n```bash\n%s\n```\n\nThe command prints:\n\n```text\n' "${title}" "${intro}" "${command}"
    (cd "${top}" && "$@" 2>&1 < /dev/null | grep -v 'archappl.conf: No such file' | sed -e 's/[[:space:]]*$//') || true
    printf '```\n\n'
}

{
    cat <<'HEADER'
# Options of the repository scripts

<!-- Generated by book/scripts/gen-script-options.bash from the help output of the scripts. Do not edit. -->

This page shows the help text that each script of the repository prints. A checkout of the repository runs every command as shown, from the root of the checkout.

HEADER
    section "The installers of the appliance" \
        "The three installers \`install-local-sqlite.bash\`, \`install-local-mariadb-uds.bash\` and \`install-local-mariadb-tcp.bash\` print the same options; the first line names the script that ran. The output below is that of the SQLite installer." \
        "bash scripts/install-local-sqlite.bash --help" \
        bash scripts/install-local-sqlite.bash --help
    section "The host package installer" \
        "This script installs the operating system packages that \`configure/os/*.pkgs\` lists." \
        "bash scripts/install_os_packages.bash --help" \
        bash scripts/install_os_packages.bash --help
    section "The real PV check" \
        "This script starts a loopback soft IOC, registers one unique PV and checks the stored samples." \
        "bash scripts/verify-local-pv.bash --help" \
        bash scripts/verify-local-pv.bash --help
    section "The test runner" \
        "This script runs the local test phases and the virtual machine operations." \
        "bash tests/run-all-tests.bash --help" \
        bash tests/run-all-tests.bash --help
    section "The appliance control script" \
        "This script is installed into the installation directory. In a checkout, where \`archappl.conf\` is not present yet, it also prints an error about the missing file before the usage; the usage below is its output." \
        "bash scripts/archappl.bash help" \
        bash scripts/archappl.bash help
} > "${output}"
printf 'wrote %s\n' "${output}"
